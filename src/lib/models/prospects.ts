/**
 * Creates and persists a prospect intelligence record.
 *
 * Persistence quality rules:
 *
 * - a prospect must have at least one valid evidence item;
 * - a prospect must explain why it fits the target product;
 * - a prospect must contain an observable opportunity / need signal;
 * - a product-linked prospect must identify the product;
 * - evidence is normalized before persistence;
 * - every evidence source must be a valid HTTP(S) URL;
 * - an email, when supplied, must have valid basic email syntax.
 *
 * Email is intentionally not yet a mandatory persistence requirement.
 * The prospecting executor will be upgraded separately to make email-first
 * prospect discovery the operational rule for task-generated prospects.
 */
export async function createProspect(
  input: CreateProspectInput
): Promise<Prospect> {
  const userId = requiredString(
    input.user_id,
    "Prospect user_id",
    500
  );

  const name = requiredString(
    input.name,
    "Prospect name",
    MAX_NAME_LENGTH
  );

  if (!isProspectType(input.prospect_type)) {
    throw new Error(
      `Invalid prospect_type "${input.prospect_type}".`
    );
  }

  const qualificationStatus =
    input.qualification_status ??
    "candidate";

  if (!isQualificationStatus(qualificationStatus)) {
    throw new Error(
      `Invalid qualification_status "${qualificationStatus}".`
    );
  }

  if (
    input.confidence !== undefined &&
    (
      !Number.isFinite(input.confidence) ||
      input.confidence < 0 ||
      input.confidence > 1
    )
  ) {
    throw new Error(
      "Prospect confidence must be between 0 and 1."
    );
  }

  const evidence = normalizeEvidence(
    input.evidence ?? []
  );

  if (evidence.length === 0) {
    throw new Error(
      "A prospect must contain at least one valid HTTP(S) evidence item."
    );
  }

  const fitReason = optionalString(
    input.fit_reason
  );

  if (!fitReason) {
    throw new Error(
      "A prospect must contain a meaningful fit_reason."
    );
  }

  const opportunitySignal = optionalString(
    input.opportunity_signal
  );

  if (!opportunitySignal) {
    throw new Error(
      "A prospect must contain a meaningful opportunity_signal."
    );
  }

  const productId =
    optionalString(input.product_id, 200);

  /*
   * Prospecting intelligence should always be associated with the product
   * that the research was performed for.
   *
   * This does not prevent future non-product prospect records, but it does
   * prevent a product-specific prospecting task from silently persisting
   * productless records.
   */
  if (input.source_task_id && !productId) {
    throw new Error(
      "A task-generated prospect must identify its target product."
    );
  }

const email =
  normalizeEmail(input.email);

/*
 * Email is now the contactability gate for task-generated prospects.
 *
 * Existing prospect records remain compatible with nullable email, but a
 * new prospect created from a task must have a syntactically valid email.
 *
 * This does NOT claim that the mailbox exists. The prospecting executor must
 * establish that the address was legitimately discovered from a public
 * source and preserve that provenance in the evidence.
 */
if (input.source_task_id && !email) {
  throw new Error(
    "A task-generated prospect must contain a valid email address."
  );
}

/*
 * For non-task-created prospects, an email is optional. If one is supplied,
 * however, it must still have valid basic syntax.
 */
if (
  !input.source_task_id &&
  input.email !== undefined &&
  input.email !== null &&
  input.email !== "" &&
  !email
) {
  throw new Error(
    "Prospect email must be a valid email address."
  );
}

  const unknowns = normalizeUnknowns(
    input.unknowns ?? []
  );

  const db = await getDb();

  const id = randomUUID();

  await db.execute({
    sql: `
      INSERT INTO prospects (
        id,
        user_id,
        source_task_id,
        name,
        organization,
        role,
        email,
        prospect_type,
        qualification_status,
        website,
        public_profile_url,
        country,
        product_id,
        fit_reason,
        opportunity_signal,
        evidence,
        confidence,
        unknowns
      )
      VALUES (
        @id,
        @user_id,
        @source_task_id,
        @name,
        @organization,
        @role,
        @email,
        @prospect_type,
        @qualification_status,
        @website,
        @public_profile_url,
        @country,
        @product_id,
        @fit_reason,
        @opportunity_signal,
        @evidence,
        @confidence,
        @unknowns
      )
    `,
    args: {
      id,

      user_id: userId,

      source_task_id:
        optionalString(
          input.source_task_id,
          200
        ) ?? null,

      name,

      organization:
        optionalString(
          input.organization,
          MAX_NAME_LENGTH
        ) ?? null,

      role:
        optionalString(
          input.role,
          MAX_NAME_LENGTH
        ) ?? null,

      email:
        email ?? null,

      prospect_type:
        input.prospect_type,

      qualification_status:
        qualificationStatus,

      website:
        optionalString(
          input.website,
          MAX_TEXT_LENGTH
        ) ?? null,

      public_profile_url:
        optionalString(
          input.public_profile_url,
          MAX_TEXT_LENGTH
        ) ?? null,

      country:
        optionalString(
          input.country,
          200
        ) ?? null,

      product_id:
        productId ?? null,

      fit_reason:
        fitReason,

      opportunity_signal:
        opportunitySignal,

      evidence:
        JSON.stringify(evidence),

      confidence:
        input.confidence ?? null,

      unknowns:
        JSON.stringify(unknowns),
    },
  });

  const result = await db.execute({
    sql: `
      SELECT *
      FROM prospects
      WHERE id = ?
        AND user_id = ?
    `,
    args: [id, userId],
  });

  const row = result.rows[0] as unknown as
    | Record<string, unknown>
    | undefined;

  if (!row) {
    throw new Error(
      "Failed to retrieve newly created prospect."
    );
  }

  return mapProspectRow(row);
}

