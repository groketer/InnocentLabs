/**
 * Prospects eligible to receive the next email in their sequence right now:
 * either they haven't started one yet (and are qualified), or they're
 * active and their next scheduled send is due.
 *
 * includePendingApproval: when Settings' require_manual_approval is
 * currently OFF, a prospect stuck in "pending_approval" from an earlier
 * run (back when approval WAS required) should become eligible again on
 * its own — the gate that put them there no longer applies. Without this,
 * turning approval off would silently do nothing for anyone already
 * caught by it; they'd stay stuck until manually approved one at a time.
 * The caller (executors/emailCampaign.ts) decides this based on the
 * current setting value.
 *
 * Still never includes unsubscribed, responded, paused, or completed —
 * those are genuinely terminal or waiting on a person's action, not on
 * settings or time.
 */
export async function listProspectsDueForOutreach(
  userId: string,
  limit: number,
  includePendingApproval = false
): Promise<Prospect[]> {
  const normalizedUserId = userId.trim();
  if (!normalizedUserId) return [];

  const db = await getDb();
  const nowIso = new Date().toISOString();

  const result = await db.execute({
    sql: `
      SELECT prospects.*
      FROM prospects
      LEFT JOIN products ON products.id = prospects.product_id
      WHERE prospects.user_id = @user_id
        AND prospects.qualification_status = 'qualified'
        AND prospects.email IS NOT NULL
        AND (products.campaign_paused IS NULL OR products.campaign_paused = false)
        AND (products.approval_status IS NULL OR products.approval_status = 'approved')
        AND (
          prospects.sequence_status = 'not_started'
          OR (prospects.sequence_status = 'active' AND prospects.next_send_at IS NOT NULL AND prospects.next_send_at <= @now)
          OR (@include_pending_approval AND prospects.sequence_status = 'pending_approval')
        )
      ORDER BY
        CASE WHEN prospects.sequence_status = 'active' THEN 0 ELSE 1 END,
        prospects.next_send_at ASC NULLS FIRST,
        prospects.created_at ASC
      LIMIT @limit
    `,
    args: {
      user_id: normalizedUserId,
      now: nowIso,
      limit: Math.min(Math.max(Math.floor(limit), 1), 200),
      include_pending_approval: includePendingApproval,
    },
  });

  return (result.rows as unknown as Array<Record<string, unknown>>).map(
    mapProspectRow
  );
}

/**
 * Narrow update for the sequence-tracking fields only. Deliberately
 * separate from updateProspect() (qualification triage) and createProspect
 * (research-derived fields) — this is the one place sending state changes.
 */
export async function updateProspectSequence(
  userId: string,
  id: string,
  fields: {
    sequence_status?: Prospect["sequence_status"];
    emails_sent?: number;
    last_sent_at?: string | null;
    next_send_at?: string | null;
    unsubscribe_token?: string;
  }
): Promise<Prospect> {
  const normalizedUserId = userId.trim();
  const normalizedId = id.trim();

  if (!normalizedUserId || !normalizedId) {
    throw new Error("A user and prospect id are required.");
  }

  const entries = Object.entries(fields).filter(
    ([, v]) => v !== undefined
  );

  if (entries.length === 0) {
    const current = await getProspectById(normalizedUserId, normalizedId);
    if (!current) throw new Error("Prospect not found.");
    return current;
  }

  const db = await getDb();

  const setClause = entries
    .map(([key]) => `${key} = @${key}`)
    .join(", ");

  const args: Record<string, unknown> = {
    id: normalizedId,
    user_id: normalizedUserId,
    updated_at: new Date().toISOString(),
  };

  for (const [key, value] of entries) {
    args[key] = value;
  }

  const result = await db.execute({
    sql: `
      UPDATE prospects
      SET ${setClause}, updated_at = @updated_at
      WHERE id = @id AND user_id = @user_id
    `,
    args,
  });

  if (result.rowsAffected === 0) {
    throw new Error("Prospect not found.");
  }

  const updated = await getProspectById(normalizedUserId, normalizedId);
  if (!updated) {
    throw new Error("Prospect was updated but could not be retrieved afterward.");
  }

  return updated;
}

