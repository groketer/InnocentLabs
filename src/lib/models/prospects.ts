/**
 * Retrieves a prospect by ID belonging to the specified user.
 *
 * Ownership is part of the query itself so a prospect belonging to another
 * user can never be returned accidentally.
 */
export async function getProspectById(
  userId: string,
  id: string
): Promise<Prospect | null> {
  const normalizedUserId = userId.trim();
  const normalizedId = id.trim();

  if (
    !normalizedUserId ||
    !normalizedId
  ) {
    return null;
  }

  const db = await getDb();

  const result = await db.execute({
    sql: `
      SELECT *
      FROM prospects
      WHERE id = ?
        AND user_id = ?
      LIMIT 1
    `,
    args: [normalizedId, normalizedUserId],
  });

  const row = result.rows[0] as unknown as
    | Record<string, unknown>
    | undefined;

  return row
    ? mapProspectRow(row)
    : null;
}

/**
 * Lists prospects belonging to a specific user, newest first.
 *
 * All filters are parameterized. The LIMIT value is normalized to prevent
 * invalid or unexpectedly large queries.
 */
export async function listProspects(
  userId: string,
  options?: {
    limit?: number;
    qualification_status?: ProspectQualificationStatus;
    prospect_type?: ProspectType;
    product_id?: string;
  }
): Promise<Prospect[]> {
  const normalizedUserId =
    userId.trim();

  if (!normalizedUserId) {
    return [];
  }

  const db = await getDb();

  const requestedLimit =
    typeof options?.limit === "number" &&
    Number.isFinite(options.limit)
      ? Math.floor(options.limit)
      : 50;

  const limit = Math.min(
    Math.max(requestedLimit, 1),
    200
  );

  const conditions: string[] = [
    "user_id = @user_id",
  ];

  const parameters: Record<
    string,
    unknown
  > = {
    user_id: normalizedUserId,
    limit,
  };

  if (options?.qualification_status) {
    if (
      !isQualificationStatus(
        options.qualification_status
      )
    ) {
      return [];
    }

    conditions.push(
      "qualification_status = @qualification_status"
    );

    parameters.qualification_status =
      options.qualification_status;
  }

  if (options?.prospect_type) {
    if (
      !isProspectType(
        options.prospect_type
      )
    ) {
      return [];
    }

    conditions.push(
      "prospect_type = @prospect_type"
    );

    parameters.prospect_type =
      options.prospect_type;
  }

  if (options?.product_id) {
    const productId =
      options.product_id.trim();

    if (!productId) {
      return [];
    }

    conditions.push(
      "product_id = @product_id"
    );

    parameters.product_id =
      productId;
  }

  const result = await db.execute({
    sql: `
      SELECT *
      FROM prospects
      WHERE ${conditions.join(" AND ")}
      ORDER BY created_at DESC
      LIMIT @limit
    `,
    args: parameters as InArgs,
  });

  const rows = result.rows as unknown as Array<
    Record<string, unknown>
  >;

  return rows.map(mapProspectRow);
}