/**
 * Prospect intelligence model.
 *
 * Milestone 3D introduces persistent prospect intelligence.
 *
 * A prospect is NOT simply a real organization or person discovered on the
 * web. A prospect is an entity for which the system has:
 *
 * 1. verified identity;
 * 2. source-backed evidence;
 * 3. a meaningful product-relevance reason; and
 * 4. a meaningful observable opportunity / need signal.
 *
 * This model deliberately does NOT represent a CRM or outreach system.
 *
 * Prospect records must not be interpreted as confirmed customers,
 * qualified buyers, or expressions of buying intent unless the evidence
 * explicitly supports those conclusions.
 *
 * Milestone 3D.9:
 *
 * - email is now a first-class prospect contact field;
 * - email remains optional at this model layer while the prospecting
 *   executor is upgraded to discover and supply legitimate usable emails;
 * - defensive JSON parsing;
 * - defensive field normalization;
 * - explicit ownership enforcement;
 * - safe filtering;
 * - protection against malformed persisted evidence;
 * - preservation of optional fields as undefined rather than fabricated data;
 * - minimum prospect-quality requirements at the persistence boundary;
 * - validation of evidence sources as HTTP(S) URLs.
 */

import { randomUUID } from "crypto";
import { getDb } from "../db";
import type { InArgs } from "@/lib/db";

export type ProspectType =
  | "person"
  | "organization"
  | "partner"
  | "investor"
  | "customer"
  | "publisher"
  | "other";

export type ProspectQualificationStatus =
  | "candidate"
  | "qualified"
  | "unqualified"
  | "needs_review";

export interface ProspectEvidence {
  observation: string;
  source: string;
  observed_at?: string;
}

export interface Prospect {
  id: string;

  user_id: string;
  source_task_id?: string;

  name: string;
  organization?: string;
  role?: string;

  /**
   * A legitimate, usable contact email discovered through research.
   *
   * This is deliberately a first-class field rather than being buried inside
   * evidence. It remains optional here because the prospecting executor is
   * responsible for establishing whether an email can be found.
   */
  email?: string;

  prospect_type: ProspectType;
  qualification_status: ProspectQualificationStatus;

  website?: string;
  public_profile_url?: string;
  /** The prospect's own country, when known — see src/lib/timezones.ts for how this drives send timing. */
  country?: string;

  product_id?: string;
  fit_reason?: string;
  opportunity_signal?: string;

  evidence: ProspectEvidence[];
  confidence?: number;
  unknowns: string[];

  /**
   * MILESTONE 3F — Follow-up campaigns.
   *
   * sequence_status starts "not_started" and moves forward as outreach
   * progresses. "pending_approval" only happens when Settings'
   * require_manual_approval is on; otherwise a sequence goes straight to
   * "active" once its first email sends.
   */
  sequence_status:
    | "not_started"
    | "pending_approval"
    | "active"
    | "completed"
    | "unsubscribed"
    | "responded"
    | "paused"
    | "in_conversation"
    | "needs_human_reply"
    | "bounced";
  emails_sent: number;
  last_sent_at?: string;
  next_send_at?: string;
  /**
   * Used to build this prospect's one-click unsubscribe link. Generated
   * once, the first time a sequence starts — never guessable, never
   * derived from anything public about the prospect.
   */
  unsubscribe_token?: string;

  /**
   * MILESTONE 4R — set when the AI checking "does this disqualified
   * prospect fit another product" is genuinely uncertain between
   * candidates, rather than confident enough to auto-reassign or
   * auto-delete. candidate_product_names holds its suggested options
   * for a person to choose from.
   */
  needs_product_decision?: boolean;
  candidate_product_names?: string[];

  created_at: string;
  updated_at: string;
}

/**
 * Input required to create a prospect.
 *
 * id and timestamps are generated by the persistence layer.
 */
export interface CreateProspectInput {
  user_id: string;
  source_task_id?: string;

  name: string;
  organization?: string;
  role?: string;

  /**
   * Optional contact email.
   *
   * The prospecting executor will be responsible for ensuring that a
   * persisted task-generated prospect has a legitimate usable email.
   */
  email?: string;

  prospect_type: ProspectType;
  qualification_status?: ProspectQualificationStatus;

  website?: string;
  public_profile_url?: string;
  country?: string;

  product_id?: string;
  fit_reason?: string;
  opportunity_signal?: string;

  evidence?: ProspectEvidence[];
  confidence?: number;
  unknowns?: string[];
}

