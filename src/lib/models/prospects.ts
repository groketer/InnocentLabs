/**
 * Retrieves a prospect by ID belonging to the specified user.
 *
 * Ownership is part of the query itself so a prospect belonging to another
 * user can never be returned accidentally.
 */
export async function getProspectById(
  userId: string,
  id: string
): Promise<Prospect | null> {
  const normalizedUserId = userId.trim();
  const normalizedId = id.trim();

  if (
    !normalizedUserId ||
    !normalizedId
  ) {
    return null;
  }

  const db = await getDb();

  const result = await db.execute({
    sql: `
      SELECT *
      FROM prospects
      WHERE id = ?
        AND user_id = ?
      LIMIT 1
    `,
    args: [normalizedId, normalizedUserId],
  });

  const row = result.rows[0] as unknown as
    | Record<string, unknown>
    | undefined;

  return row
    ? mapProspectRow(row)
    : null;
}

/**
 * Lists prospects belonging to a specific user, newest first.
 *
 * All filters are parameterized. The LIMIT value is normalized to prevent
 * invalid or unexpectedly large queries.
 */
export async function listProspects(
  userId: string,
  options?: {
    limit?: number;
    qualification_status?: ProspectQualificationStatus;
    prospect_type?: ProspectType;
    product_id?: string;
  }
): Promise<Prospect[]> {
  const normalizedUserId =
    userId.trim();

  if (!normalizedUserId) {
    return [];
  }

  const db = await getDb();

  const requestedLimit =
    typeof options?.limit === "number" &&
    Number.isFinite(options.limit)
      ? Math.floor(options.limit)
      : 50;

  const limit = Math.min(
    Math.max(requestedLimit, 1),
    200
  );

  const conditions: string[] = [
    "user_id = @user_id",
  ];

  const parameters: Record<
    string,
    unknown
  > = {
    user_id: normalizedUserId,
    limit,
  };

  if (options?.qualification_status) {
    if (
      !isQualificationStatus(
        options.qualification_status
      )
    ) {
      return [];
    }

    conditions.push(
      "qualification_status = @qualification_status"
    );

    parameters.qualification_status =
      options.qualification_status;
  }

  if (options?.prospect_type) {
    if (
      !isProspectType(
        options.prospect_type
      )
    ) {
      return [];
    }

    conditions.push(
      "prospect_type = @prospect_type"
    );

    parameters.prospect_type =
      options.prospect_type;
  }

  if (options?.product_id) {
    const productId =
      options.product_id.trim();

    if (!productId) {
      return [];
    }

    conditions.push(
      "product_id = @product_id"
    );

    parameters.product_id =
      productId;
  }

  const result = await db.execute({
    sql: `
      SELECT *
      FROM prospects
      WHERE ${conditions.join(" AND ")}
      ORDER BY created_at DESC
      LIMIT @limit
    `,
    args: parameters as InArgs,
  });

  const rows = result.rows as unknown as Array<
    Record<string, unknown>
  >;

  return rows.map(mapProspectRow);
}

/**
 * Updates a prospect's qualification status.
 *
 * This is intentionally narrow — the Prospects view lets a person triage
 * (qualified / not a fit / needs review) what the research already
 * gathered. It does not let evidence, contact details, or other
 * research-derived fields be edited here; those come only from the
 * prospecting executor's own evidence-backed process.
 */
export async function updateProspect(
  userId: string,
  id: string,
  fields: { qualification_status: ProspectQualificationStatus }
): Promise<Prospect> {
  const normalizedUserId = userId.trim();
  const normalizedId = id.trim();

  if (!normalizedUserId || !normalizedId) {
    throw new Error("A user and prospect id are required.");
  }

  if (!isQualificationStatus(fields.qualification_status)) {
    throw new Error(
      `"${fields.qualification_status}" is not a valid qualification status.`
    );
  }

  const db = await getDb();

  const result = await db.execute({
    sql: `
      UPDATE prospects
      SET
        qualification_status = @qualification_status,
        updated_at = @updated_at
      WHERE id = @id
        AND user_id = @user_id
    `,
    args: {
      id: normalizedId,
      user_id: normalizedUserId,
      qualification_status: fields.qualification_status,
      updated_at: new Date().toISOString(),
    },
  });

  if (result.rowsAffected === 0) {
    throw new Error("Prospect not found.");
  }

  const updated = await getProspectById(normalizedUserId, normalizedId);

  if (!updated) {
    throw new Error("Prospect was updated but could not be retrieved afterward.");
  }

  return updated;
}

/**
 * MILESTONE 3S — genuine deep qualification.
 *
 * Applies the result of an actual research-driven qualification pass —
 * not the old one-line "confidence >= threshold" check against a number
 * assigned once during discovery, but a real decision made after fresh,
 * targeted research specifically about whether THIS prospect should be
 * qualified. Updates confidence and fit_reason to reflect that fresh
 * research, and appends any new evidence found along the way rather than
 * discarding it.
 */
export async function applyDeepQualificationResult(
  userId: string,
  prospectId: string,
  result: {
    qualification_status: "qualified" | "unqualified";
    confidence: number;
    fit_reason: string;
    additional_evidence: ProspectEvidence[];
  }
): Promise<Prospect> {
  const normalizedUserId = userId.trim();
  const normalizedId = prospectId.trim();

  if (!normalizedUserId || !normalizedId) {
    throw new Error("A user and prospect id are required.");
  }

  const existing = await getProspectById(normalizedUserId, normalizedId);
  if (!existing) {
    throw new Error("Prospect not found.");
  }

  const mergedEvidence = [
    ...existing.evidence,
    ...result.additional_evidence,
  ];

  const db = await getDb();

  await db.execute({
    sql: `
      UPDATE prospects
      SET
        qualification_status = @qualification_status,
        confidence = @confidence,
        fit_reason = @fit_reason,
        evidence = @evidence,
        updated_at = @updated_at
      WHERE id = @id
        AND user_id = @user_id
    `,
    args: {
      id: normalizedId,
      user_id: normalizedUserId,
      qualification_status: result.qualification_status,
      confidence: result.confidence,
      fit_reason: result.fit_reason,
      evidence: JSON.stringify(mergedEvidence),
      updated_at: new Date().toISOString(),
    },
  });

  const updated2 = await getProspectById(normalizedUserId, normalizedId);
  if (!updated2) {
    throw new Error("Prospect was updated but could not be retrieved afterward.");
  }
  return updated2;
}

